package vercel

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

const (
	surfaceBegin = "<!-- surface:begin (generated by TestVercelDocListsTheSurfaceTheModelServes; UPDATE_VERCEL_DOC=1 rewrites it) -->"
	surfaceEnd   = "<!-- surface:end -->"
)

// surfaceTable renders every operation the model serves as a row: what it is
// called, where it answers (the document's address and every other one), and
// what its answers are held to. It is read from the booted model and the two
// documents the conformance run uses, so it cannot claim an operation is served
// that is not, or validated when it is not.
func surfaceTable(t *testing.T) string {
	t.Helper()
	c := newConf(t)
	names := make([]string, 0, len(c.ops))
	for n := range c.ops {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("| Operation | Method and address | Also answers at | Status |\n|---|---|---|---|\n")
	for _, n := range names {
		op := c.ops[n]
		also := "-"
		if len(op.alts) > 0 {
			quoted := make([]string, len(op.alts))
			for i, a := range op.alts {
				quoted[i] = "`" + a + "`"
			}
			also = strings.Join(quoted, ", ")
		}
		status := op.provenance()
		switch status {
		case "undocumented":
			status = "authored (mirror's own control route, off unless started with MIRROR_VERCEL_FAULTS)"
		case "authored":
			status = "authored (held to the supplement's schema)"
		}
		if reason, ok := confUncovered[n]; ok {
			status = "authored (driven end to end; " + strings.SplitN(reason, ";", 2)[0] + ")"
		}
		if _, ok := confBinaryBody[n]; ok {
			status += "; the body is bytes, so only the status is held"
		}
		fmt.Fprintf(&b, "| `%s` | %s `%s` | %s | %s |\n", n, op.method, op.uri, also, status)
	}
	return b.String()
}

// TestVercelDocListsTheSurfaceTheModelServes keeps docs/VERCEL.md's table of the
// supported surface equal to what is served. Rewrite it with
// UPDATE_VERCEL_DOC=1 after adding or moving an operation.
func TestVercelDocListsTheSurfaceTheModelServes(t *testing.T) {
	path := filepath.Join("..", "..", "..", "docs", "VERCEL.md")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	doc := string(raw)
	i, j := strings.Index(doc, surfaceBegin), strings.Index(doc, surfaceEnd)
	if i < 0 || j < i {
		t.Fatalf("docs/VERCEL.md has no %q ... %q region", surfaceBegin, surfaceEnd)
	}
	want := surfaceBegin + "\n\n" + surfaceTable(t) + "\n" + surfaceEnd
	if os.Getenv("UPDATE_VERCEL_DOC") == "1" {
		out := doc[:i] + want + doc[j+len(surfaceEnd):]
		if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if got := doc[i : j+len(surfaceEnd)]; got != want {
		t.Fatalf("the table in docs/VERCEL.md is not the surface the model serves; run UPDATE_VERCEL_DOC=1 go test ./test/behavior/vercel -run TestVercelDocListsTheSurface")
	}
}
